function makeQuestions(subject: QuizQ['subject'], rows: Question[]): QuizQ[] {
  return rows.map(([id, grade, q, choices, hint, explain]) => ({
    id: `c2_${id}`, subject, grade, tier: grade === 3 ? 1 : grade === 4 ? 2 : 3,
    q, choices, answer: 0, hint, explain,
  }));
}

