function makeQuestions(subject: Subject, rows: Row[]): QuizQ[] {
  return rows.map(([id, grade, q, choices, hint, explain]) => ({
    id: `c3_${subject}_${id}`, subject, grade, tier: grade === 3 ? 1 : grade === 4 ? 2 : 3,
    q, choices, answer: 0, hint, explain,
  }));
}

